import { readFileSync } from 'node:fs';
const S = process.argv[2];
const base = 'http://127.0.0.1:3001/api/v1';
const tag = Date.now().toString(36);
let passed = 0, failed = 0;
const check = (n, ok, d) => { if (ok) { passed++; console.log('PASS', n); } else { failed++; console.log('FAIL', n, d === undefined ? '' : JSON.stringify(d).slice(0, 400)); } };
let T;
const call = async (m, p, b) => { const r = await fetch(base + p, { method: m, headers: { 'content-type': 'application/json', origin: 'http://localhost:4173', ...(T ? { authorization: `Bearer ${T}` } : {}) }, body: b ? JSON.stringify(b) : undefined }); const j = await r.json().catch(() => null); return { status: r.status, data: j?.data, j }; };
const email = `rank-${tag}@example.test`;
T = (await call('POST', '/auth/signup', { email, password: 'Str0ng!Passw0rd#22', name: 'rank' })).data.token;
const pid = (await call('POST', '/projects', { name: 'R', domain: 'serp-demo.rankforge.test', country: 'IR', language: 'fa' })).data.id;
await call('POST', `/projects/${pid}/keywords`, { keywords: ['تور کیش', 'بلیط هواپیما'] });
const queued = await call('POST', `/projects/${pid}/rankings/check`, {});
check('a rank check is accepted with only SerpApi configured', queued.status === 201, queued.j);
const jobId = queued.data?.job?.id;
let job;
for (let i = 0; i < 60; i++) { job = ((await call('GET', `/jobs?projectId=${pid}`)).data ?? []).find((j) => j.id === jobId); if (['completed', 'failed', 'dead_letter'].includes(job?.status)) break; await new Promise((r) => setTimeout(r, 500)); }
check('the worker completes the check', job?.status === 'completed', job);
const ranks = (await call('GET', `/projects/${pid}/rankings`)).data ?? [];
const kish = ranks.find((r) => r.keyword === 'تور کیش');
const flight = ranks.find((r) => r.keyword === 'بلیط هواپیما');
check('the ranked keyword gets its exact position', kish?.position === 14, kish);
check('the ranking page URL is stored', kish?.url === 'https://www.serp-demo.rankforge.test/tours/kish');
check('the source is recorded', kish?.provider === 'serpapi', kish);
check('a keyword outside the depth has no position', flight && flight.position === null, flight);
const log = readFileSync(`${S}/serp.log`, 'utf8').trim().split('\n').map((l) => JSON.parse(l)).filter((p) => p.q === 'تور کیش' || p.q === 'بلیط هواپیما');
const kishCalls = log.filter((p) => p.q === 'تور کیش');
const flightCalls = log.filter((p) => p.q === 'بلیط هواپیما');
check('searching stops once the site is found (2 searches)', kishCalls.length === 2, kishCalls.length);
check('an unranked keyword uses exactly the depth (3 searches)', flightCalls.length === 3, flightCalls.length);
check('Iran and Persian are requested', log.every((p) => p.gl === 'ir' && p.hl === 'fa' && p.engine === 'google'), log[0]);
const kw = (await call('GET', `/projects/${pid}/keywords`)).data;
const list = Array.isArray(kw) ? kw : kw?.keywords ?? kw?.items ?? [];
check('keywords follow the project country and language', list.every((k) => k.country === 'IR' && k.language === 'fa'), list[0]);
check('the job reports the searches used (2 + 3)', job?.result?.searches === 5 && job?.result?.provider === 'serpapi', job?.result);
console.log(JSON.stringify({ email, pid }));
console.log(`\n${passed} passed, ${failed} failed`);
process.exit(failed ? 1 : 0);
