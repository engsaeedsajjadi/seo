const KEY = 'seoyar_menu_help';

/** Whether menu help is shown; remembered in this browser, on by default. */
export function useMenuHelp(): [boolean, () => void] {
  const [on, setOn] = useState(true);
  useEffect(() => {
    try { if (localStorage.getItem(KEY) === 'off') setOn(false); } catch { /* storage blocked: stays on */ }
  }, []);
  const toggle = useCallback(() => {
    setOn((value) => {
      try { localStorage.setItem(KEY, value ? 'off' : 'on'); } catch { /* not remembered */ }
      return !value;
    });
  }, []);
  return [on, toggle];
}
